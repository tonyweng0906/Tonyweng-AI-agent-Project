"""API-free portfolio demo; production application remains in frontend.py."""
import csv
import json
import re
import sqlite3
from datetime import date, timedelta
from pathlib import Path

import streamlit as st
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

ROOT = Path(__file__).resolve().parents[1]
REPO = 'https://github.com/tonyweng0906/Tonyweng-AI-agent-Project'


@st.cache_resource
def knowledge_index():
    with (ROOT / 'data/knowledge_base.csv').open(encoding='utf-8') as f:
        docs = list(csv.DictReader(f))
    vectorizer = TfidfVectorizer(stop_words='english', ngram_range=(1, 2))
    matrix = vectorizer.fit_transform([d['title'] + ' ' + d['content'] for d in docs])
    return docs, vectorizer, matrix


def retrieve(query):
    docs, vectorizer, matrix = knowledge_index()
    scores = cosine_similarity(vectorizer.transform([query]), matrix)[0]
    return [(docs[i], float(scores[i])) for i in scores.argsort()[::-1][:3] if scores[i] > 0.05]


def sample_query(day, hour):
    # In-memory, read-only query over deterministic synthetic slots. No customer data.
    with sqlite3.connect(':memory:') as db:
        db.row_factory = sqlite3.Row
        db.execute('CREATE TABLE slots (court TEXT, day TEXT, hour INTEGER, available INTEGER)')
        rows = [(f'Court {c}', day.isoformat(), h, int((day.toordinal() + c + h) % 3 != 0))
                for c in range(1, 9) for h in range(9, 22)]
        db.executemany('INSERT INTO slots VALUES (?, ?, ?, ?)', rows)
        sql = 'SELECT court, day, hour FROM slots WHERE day = ? AND hour = ? AND available = 1 ORDER BY court'
        result = [dict(r) for r in db.execute(sql, (day.isoformat(), hour))]
    return sql, result


